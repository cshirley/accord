import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadFeatureDocs } from "./feature-doc.js";

export interface FeatureIndexOptions {
  repoRoot: string;
  /** Default: docs/features. */
  root?: string;
}

export interface FeatureIndexResult {
  indexMd: string;
  indexJson: string;
}

/** Writes index.md and index.json under repoRoot/root and returns their contents. */
export function generateFeatureIndex(options: FeatureIndexOptions): FeatureIndexResult {
  const root = options.root ?? "docs/features";
  const docs = loadFeatureDocs(options.repoRoot, root);

  const indexJson = `${JSON.stringify(
    {
      features: docs.map((doc) => ({
        id: doc.id,
        title: doc.title,
        description: doc.description,
        tags: doc.tags,
        status: doc.status,
        owners: doc.owners,
        acs: doc.acs,
        anchors: doc.anchors,
        depends_on: doc.depends_on,
        related: doc.related,
        supersedes: doc.supersedes,
        path: doc.path,
      })),
    },
    null,
    2,
  )}\n`;

  const rows = docs.map(
    (doc) =>
      `| [${doc.id}](${doc.path}) | ${doc.title} | ${doc.status} | ${doc.acs.length} | ${doc.description.replace(/\|/g, "\\|")} |`,
  );
  const indexMd = `${[
    "# Feature index",
    "",
    "<!-- Generated by the feature index generator. Do not edit. -->",
    "",
    "| Feature | Title | Status | ACs | Description |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n")}\n`;

  const dir = join(options.repoRoot, root);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "index.md"), indexMd);
  writeFileSync(join(dir, "index.json"), indexJson);
  return { indexMd, indexJson };
}
