/**
 * Pure converters used by `accord-sync`: pi config → Claude Code / Codex formats.
 * No I/O, no host imports.
 */

export const GENERATED_MARKER = "<!-- generated by accord-sync; edit the pi source instead -->";

const CLAUDE_TOOL: Record<string, string> = {
  read: "Read",
  grep: "Grep",
  find: "Glob",
  ls: "Glob",
  bash: "Bash",
  write: "Write",
  edit: "Edit",
};

export type PiAgent = {
  name: string;
  description: string;
  tools: string[];
  body: string;
};

/** Minimal frontmatter parser for the flat/one-level-map shape pi agents use. */
export function parsePiAgent(source: string): PiAgent | null {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(source);
  if (!m) return null;
  const meta: Record<string, string> = {};
  const tools: string[] = [];
  let inTools = false;
  for (const line of m[1].split("\n")) {
    const tool = /^\s{2,}([\w-]+):\s*(true|false)\s*$/.exec(line);
    if (inTools && tool) {
      if (tool[2] === "true") tools.push(tool[1]);
      continue;
    }
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    inTools = kv[1] === "tools" && kv[2] === "";
    meta[kv[1]] = kv[2].replace(/^["']|["']$/g, "");
  }
  if (!meta.name) return null;
  return { name: meta.name, description: meta.description ?? "", tools, body: m[2].trim() };
}

export function toClaudeAgent(agent: PiAgent): string {
  const tools = [...new Set(agent.tools.map((t) => CLAUDE_TOOL[t]).filter(Boolean))];
  const desc = agent.description.replace(/"/g, '\\"');
  return [
    "---",
    `name: ${agent.name}`,
    `description: "${desc}"`,
    ...(tools.length ? [`tools: ${tools.join(", ")}`] : []),
    "---",
    GENERATED_MARKER,
    "",
    agent.body,
    "",
  ].join("\n");
}

export type PiMcpServer = {
  enabled?: boolean;
  command?: string;
  args?: string[];
  env?: Record<string, string>;
  url?: string;
  [key: string]: unknown;
};

/** Enabled servers only; pi-only keys (`exposure`, `enabled`) dropped. */
export function toClaudeMcp(servers: Record<string, PiMcpServer>): {
  mcpServers: Record<string, unknown>;
} {
  const out: Record<string, unknown> = {};
  for (const [name, s] of Object.entries(servers)) {
    if (s.enabled === false) continue;
    if (s.url) out[name] = { type: "http", url: s.url };
    else if (s.command)
      out[name] = { command: s.command, args: s.args ?? [], ...(s.env ? { env: s.env } : {}) };
  }
  return { mcpServers: out };
}

const tomlStr = (v: string) => JSON.stringify(v);

/** Codex `config.toml` MCP snippet (stdio servers only; Codex http needs a bridge). */
export function toCodexToml(servers: Record<string, PiMcpServer>): string {
  const lines = ["# generated by accord-sync; append to ~/.codex/config.toml"];
  for (const [name, s] of Object.entries(servers)) {
    if (s.enabled === false || !s.command) continue;
    lines.push(
      "",
      `[mcp_servers.${name.replace(/[^\w-]/g, "_")}]`,
      `command = ${tomlStr(s.command)}`,
    );
    lines.push(`args = [${(s.args ?? []).map(tomlStr).join(", ")}]`);
    if (s.env && Object.keys(s.env).length) {
      lines.push(`[mcp_servers.${name.replace(/[^\w-]/g, "_")}.env]`);
      for (const [k, v] of Object.entries(s.env)) lines.push(`${k} = ${tomlStr(v)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

const PI_ONLY_REF =
  /\b(wt_(?:exec|create|list|merge|pr|remove|status)|tool_search|git_worktree_resolve|git_review_(?:context|tasks)|git_commit_(?:context|execute)|gh_(?:pr_context|pr_submit|ci_context)|pr_review_(?:context|post|report)|repo_verify|repo_harness_context|dev_[a-z_]+|thrift_recall)\b/g;

/** Names of pi-only tools a skill body references (portability lint). */
export function findPiOnlyRefs(skillMarkdown: string): string[] {
  return [...new Set(skillMarkdown.match(PI_ONLY_REF) ?? [])].sort();
}
