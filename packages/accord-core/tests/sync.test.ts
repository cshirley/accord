import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, readlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  applySync,
  findPiOnlyRefs,
  parsePiAgent,
  planSync,
  toClaudeAgent,
  toClaudeMcp,
  toCodexToml,
} from "../src/sync/index.js";

const agentMd = `---\nname: default\ndescription: "General Purpose Agent"\ntier: workhorse\ntools:\n  read: true\n  grep: true\n  find: true\n  bash: true\n  write: false\n---\n\nYou do things.\n`;

describe("sync converters", () => {
  test("pi agent → Claude agent maps tools, drops tier", () => {
    const out = toClaudeAgent(parsePiAgent(agentMd) as never);
    expect(out).toContain("tools: Read, Grep, Glob, Bash");
    expect(out).not.toContain("Write");
    expect(out).not.toContain("tier");
    expect(out).toContain("generated by accord-sync");
  });
  test("MCP: disabled dropped, pi-only keys stripped, http vs stdio", () => {
    const c = toClaudeMcp({
      a: { enabled: false, command: "x" },
      b: { command: "npx", args: ["-y", "p"], exposure: "deferred" },
      c: { url: "https://h/mcp" },
    }).mcpServers;
    expect(Object.keys(c)).toEqual(["b", "c"]);
    expect(JSON.stringify(c)).not.toContain("exposure");
    expect(toCodexToml({ b: { command: "npx", args: ["-y"] } })).toContain("[mcp_servers.b]");
  });
  test("pi-only ref lint", () => {
    expect(findPiOnlyRefs("use wt_exec and repo_verify, not cd")).toEqual([
      "repo_verify",
      "wt_exec",
    ]);
  });
});

describe("planSync/applySync", () => {
  function fixture() {
    const home = mkdtempSync(join(tmpdir(), "sync-"));
    const skills = join(home, ".config/pi/agent/skills");
    mkdirSync(join(skills, "rfc"), { recursive: true });
    writeFileSync(join(skills, "rfc/SKILL.md"), "---\nname: rfc\ndescription: d\n---\n");
    mkdirSync(join(home, ".config/pi/agent/agents"), { recursive: true });
    writeFileSync(join(home, ".config/pi/agent/agents/default.md"), agentMd);
    return { home, skills };
  }
  test("links skills to Claude only by default; idempotent", () => {
    const { home, skills } = fixture();
    const input = { home, skillSources: [skills] };
    applySync(planSync(input));
    expect(readlinkSync(join(home, ".claude/skills/rfc"))).toBe(join(skills, "rfc"));
    expect(() => readlinkSync(join(home, ".agents/skills/rfc"))).toThrow();
    expect(readFileSync(join(home, ".claude/agents/default.md"), "utf8")).toContain(
      "name: default",
    );
    expect(planSync(input).some((a) => a.kind === "link")).toBe(false);
  });
  test("--codex also links canonical dir", () => {
    const { home, skills } = fixture();
    applySync(planSync({ home, skillSources: [skills], codex: true }));
    expect(readlinkSync(join(home, ".agents/skills/rfc"))).toBe(join(skills, "rfc"));
  });
  test("never overwrites a hand-written agent file", () => {
    const { home, skills } = fixture();
    mkdirSync(join(home, ".claude/agents"), { recursive: true });
    writeFileSync(join(home, ".claude/agents/default.md"), "mine");
    applySync(planSync({ home, skillSources: [skills] }));
    expect(readFileSync(join(home, ".claude/agents/default.md"), "utf8")).toBe("mine");
  });
});
